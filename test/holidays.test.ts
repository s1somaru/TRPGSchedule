// 祝日の計算が、内閣府の祝日一覧(syukujitsu.csv)と同じになるか
import { describe, expect, it } from "vitest";
import { holidayName, holidaysOfYear } from "../src/shared/holidays";

const list = (y: number) => Object.fromEntries([...holidaysOfYear(y).entries()].sort(([a], [b]) => a.localeCompare(b)));

describe("祝日", () => {
  it("2025年(日曜の祝日の振替がある年)", () => {
    expect(list(2025)).toEqual({
      "2025-01-01": "元日",
      "2025-01-13": "成人の日",
      "2025-02-11": "建国記念の日",
      "2025-02-23": "天皇誕生日",
      "2025-02-24": "振替休日",
      "2025-03-20": "春分の日",
      "2025-04-29": "昭和の日",
      "2025-05-03": "憲法記念日",
      "2025-05-04": "みどりの日",
      "2025-05-05": "こどもの日",
      "2025-05-06": "振替休日",
      "2025-07-21": "海の日",
      "2025-08-11": "山の日",
      "2025-09-15": "敬老の日",
      "2025-09-23": "秋分の日",
      "2025-10-13": "スポーツの日",
      "2025-11-03": "文化の日",
      "2025-11-23": "勤労感謝の日",
      "2025-11-24": "振替休日",
    });
  });

  it("2024年は振替休日が5回あり、21日になる", () => {
    expect(holidaysOfYear(2024).size).toBe(21);
    expect(holidayName("2024-09-23")).toBe("振替休日");
    expect(holidayName("2024-11-04")).toBe("振替休日");
  });

  it("2026年(9月に国民の休日がある年)", () => {
    expect(list(2026)).toEqual({
      "2026-01-01": "元日",
      "2026-01-12": "成人の日",
      "2026-02-11": "建国記念の日",
      "2026-02-23": "天皇誕生日",
      "2026-03-20": "春分の日",
      "2026-04-29": "昭和の日",
      "2026-05-03": "憲法記念日",
      "2026-05-04": "みどりの日",
      "2026-05-05": "こどもの日",
      "2026-05-06": "振替休日",
      "2026-07-20": "海の日",
      "2026-08-11": "山の日",
      "2026-09-21": "敬老の日",
      "2026-09-22": "国民の休日",
      "2026-09-23": "秋分の日",
      "2026-10-12": "スポーツの日",
      "2026-11-03": "文化の日",
      "2026-11-23": "勤労感謝の日",
    });
  });

  it("2027年", () => {
    expect(list(2027)).toEqual({
      "2027-01-01": "元日",
      "2027-01-11": "成人の日",
      "2027-02-11": "建国記念の日",
      "2027-02-23": "天皇誕生日",
      "2027-03-21": "春分の日",
      "2027-03-22": "振替休日",
      "2027-04-29": "昭和の日",
      "2027-05-03": "憲法記念日",
      "2027-05-04": "みどりの日",
      "2027-05-05": "こどもの日",
      "2027-07-19": "海の日",
      "2027-08-11": "山の日",
      "2027-09-20": "敬老の日",
      "2027-09-23": "秋分の日",
      "2027-10-11": "スポーツの日",
      "2027-11-03": "文化の日",
      "2027-11-23": "勤労感謝の日",
    });
  });

  it("2020・2021年はオリンピックで移った日を使う", () => {
    expect(holidayName("2020-07-23")).toBe("海の日");
    expect(holidayName("2020-07-24")).toBe("スポーツの日");
    expect(holidayName("2020-08-10")).toBe("山の日");
    expect(holidayName("2020-07-20")).toBeUndefined();
    expect(holidayName("2020-10-12")).toBeUndefined();
    expect(holidayName("2021-07-22")).toBe("海の日");
    expect(holidayName("2021-07-23")).toBe("スポーツの日");
    expect(holidayName("2021-08-08")).toBe("山の日");
    expect(holidayName("2021-08-09")).toBe("振替休日");
    expect(holidayName("2021-08-11")).toBeUndefined();
  });

  it("祝日でない日と、対応していない年は undefined", () => {
    expect(holidayName("2026-10-27")).toBeUndefined();
    expect(holidayName("2019-01-01")).toBeUndefined();
    expect(holidayName("2100-01-01")).toBeUndefined();
  });

  it("どの年も祝日は 16〜22 日に収まる(計算のずれの見張り)", () => {
    for (let y = 2020; y <= 2099; y++) {
      const n = holidaysOfYear(y).size;
      expect(n, String(y)).toBeGreaterThanOrEqual(16);
      expect(n, String(y)).toBeLessThanOrEqual(22);
    }
  });
});
